          <div style="text-align:justify;">
            <p2>Ethical Clearence merupakan instrumen pengukuran dalam keberterimaan secara etik dalam suatu rangkaian proses penelitian, yang bertujuan untuk melindungi subjek. Sehingga, disaat melakukan penelitian, perspektif kita harus menggunakan perspektif pemenuhan hak asasi manusia. Kita perlu memastikan bahwa penelitian yang sedang kita lakukan tidak mengekspliotasi subjek partisipan, tidak melakukan pelanggaran pada hak subjek partisipan, memberikan hak kepada partisipan untuk mengeluarkan pendapat, hak mendapatkan perlindungan privasinya, dan hak untuk tidak dieksploitasi. Hal ini merupakan sesuatu yang sangat penting, mengingat penelitian yang baik bukan semata-mata penelitian yang bisa diselesaikan, tetapi memenuhi hak subjek partisipan.

            <br> <br>

            Ketua Pengurus Komisi Etik Penelitian Universitas Pendidikan Indonesia Periode 2023-2028 Prof. Dr. Budi Mulyanti, M.T., menyampaikan pernyataan tegas tersebut dalam sebuah wawancara, setelah menerima Surat Keputusan Rektor Universitas Pendidikan Indonesia Nomor 1745/UN40/HK/2023 Tentang Pengurus Komisi Etik Penelitian Universitas Pendidikan Indonesia Periode 2023-2028 di Gedung University Centre (UC) UPI, Ruang Teleconference lantai 1, Kampus UPI Jalan Dr. Setiabudhi Nomor 229 Bandung, Senin, (2/10/2023).

            <br> <br>

            Dalam pernyataannya Prof. Budi Mulyanti menambahkan, ”Artinya, ethical clearance menjadi sebuah bentuk proteksi pertama untuk memastikan apakah penelitian ini bisa dilakukan atau tidak. Selain aspek metodologis, yang harus diperhatikan juga adalah aspek etikanya. Kadang-kadang satu penelitian bisa gagal dilakukan karena walaupun secara metodologi bisa dilakukan, tapi dia tidak bisa memenuhi aspek etikanya. Kita tentu tidak ingin UPI nanti dianggap menjadi lembaga yang tidak memperdulikan hak-hak dari partisipan tadi.”

            Prof. Budi Mulyanti menyatakan, agar para peneliti sebelum melakukan penelitiannya harus meminta izin terlebih dahulu. Perizinan tersebut apakah penelitian tersebut melanggar atau tidak terhadap subjek yang diteliti, terutama pada manusia dan hewan, dengan adanya surat ethical clearance yang menyatakan bahwa penelitian tersebut tidak melanggar atau tidak akan merugikan subjek, maka penelitian dapat dilanjutkan.
            <br><br>
            Namun apabila Komisi Etik Penelitian meyakini akan adanya kerugian terhadap subjek manusia atau hewan, maka peneliti tersebut tidak dapat melakukan penelitian selanjutnya, atau peneliti harus merubah subjek penelitiannya.
            <br><br>
            “Jadi intinya bahwa ethical clearance ini adalah untuk melindungi subjek penelitian terutama adalah hewan dan manusia agar tidak merugikan subjek. Subjek itu bukan betul-betul jadi objek tapi dia adalah subjeknya,” ungkap Prof. Budi Mulyanti.
            <br><br>
            Prof. Budi Mulyanti menambahkan, diterbitkannya ethical clearance, merupakan keharusan bagi seorang peneliti, ditambah ini merupakan tuntutan bagi perguruan tinggi yang ingin menuju World Class University. Jika UPI ingin memiliki predikat WCU, maka salah satu syarat agar dapat memenuhi predikat tersebut adalah penelitian-penelitian yang dilakukan oleh UPI harus memilki surat ethical clearance. Beberapa jurnal internasional memiliki persyaratan agar sebelum publish harus melampirkan surat ethical clearance pada risetnya.
